# update-deps.ps1 - 生成本地开发依赖总览（DEPENDENCIES.md）
#
# 用法：
#   powershell -NoProfile -ExecutionPolicy Bypass -File scripts\update-deps.ps1
#   powershell ... -File scripts\update-deps.ps1 -SkipDocker   # 跳过 Docker 镜像枚举（更快）
#
# 输出：仓库根目录 DEPENDENCIES.md（AGENTS.md §5 引用的自动生成清单）
# 所有外部命令均 try/catch 包裹，工具缺失时标注 not found，绝不硬失败。

param(
    [string]$OutputPath = "",
    [switch]$SkipDocker
)

$ErrorActionPreference = "Continue"
$REPO_ROOT = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)  # scripts/ 的上一级 = 仓库根
if ($OutputPath -eq "") { $OutputPath = Join-Path $REPO_ROOT "DEPENDENCIES.md" }

$lines = New-Object System.Collections.Generic.List[string]
$now = Get-Date -Format "yyyy-MM-dd HH:mm"

function Add-Line([string]$s) { $lines.Add($s) | Out-Null }

function Get-ToolVersion([string]$name, [string]$args = "--version") {
    try {
        $cmd = Get-Command $name -ErrorAction Stop
        $out = & $cmd.Source $args 2>$null
        if ($LASTEXITCODE -ne 0 -and -not $out) { return "found ($($cmd.Source))" }
        $first = ($out | Select-Object -First 1)
        if ($first) { return ($first.ToString().Trim()) } else { return "found ($($cmd.Source))" }
    } catch {
        return "not found"
    }
}

Add-Line "# Local Development Dependencies"
Add-Line ""
Add-Line "> Auto-generated by scripts/update-deps.ps1, last updated: $now"
Add-Line "> Update command: ``powershell scripts/update-deps.ps1``"
Add-Line ""
Add-Line "---"
Add-Line ""

# ── Disk Space ──
Add-Line "## Disk Space"
Add-Line ""
Add-Line "| Drive | Total | Free | Used |"
Add-Line "|---|---|---|---|"
try {
    foreach ($d in (Get-PSDrive -PSProvider FileSystem)) {
        if (-not $d.Free -or -not $d.Used) { continue }
        $totalGB = [Math]::Round(($d.Used + $d.Free) / 1GB, 1)
        $freeGB = [Math]::Round($d.Free / 1GB, 1)
        $usedPct = if (($d.Used + $d.Free) -gt 0) { [Math]::Round($d.Used / ($d.Used + $d.Free) * 100, 1) } else { 0 }
        Add-Line "| $($d.Name): | ${totalGB}GB | ${freeGB}GB | ${usedPct}% |"
    }
} catch { Add-Line "| (disk query failed: $($_.Exception.Message)) | | | |" }
Add-Line ""
Add-Line "---"
Add-Line ""

# ── Runtimes and Tools ──
Add-Line "## Runtimes and Tools"
Add-Line ""
Add-Line "### System Runtimes"
Add-Line "| Tool | Version |"
Add-Line "|---|---|"
foreach ($t in @("node", "npm", "python", "pip", "go", "git", "docker", "uv")) {
    $v = Get-ToolVersion $t
    Add-Line "| $t | $v |"
}
try {
    $sqlite = python -c "import sqlite3; print('SQLite', sqlite3.sqlite3_version, '(python built-in)')" 2>$null
    if ($sqlite) { Add-Line "| $sqlite | |" }
} catch { }
Add-Line ""
Add-Line ""

# ── JDK ──
Add-Line "### JDK (Java)"
Add-Line "| Version | Path |"
Add-Line "|---|---|"
try {
    $jdkRoot = Join-Path $env:USERPROFILE ".jdks"
    if (Test-Path $jdkRoot) {
        foreach ($jdk in (Get-ChildItem $jdkRoot -Directory)) {
            Add-Line "| $($jdk.Name) | ``$($jdk.FullName)`` |"
        }
    } else { Add-Line "| (no ~/.jdks) | |" }
} catch { Add-Line "| (JDK scan failed) | |" }
Add-Line ""

# ── Android SDK ──
Add-Line "### Android SDK"
Add-Line "| Component | Value |"
Add-Line "|---|---|"
try {
    $sdk = $env:ANDROID_HOME
    if (-not $sdk) { $sdk = Join-Path $env:LOCALAPPDATA "Android\Sdk" }
    if (Test-Path $sdk) {
        $plat = Join-Path $sdk "platforms"
        $bt = Join-Path $sdk "build-tools"
        $plats = if (Test-Path $plat) { ((Get-ChildItem $plat -Directory | ForEach-Object { $_.Name }) -join ", ") } else { "not found" }
        $bts = if (Test-Path $bt) { ((Get-ChildItem $bt -Directory | ForEach-Object { $_.Name }) -join ", ") } else { "not found" }
        Add-Line "| platforms | $plats |"
        Add-Line "| build-tools | $bts |"
        Add-Line "| path | ``$sdk`` |"
    } else { Add-Line "| (Android SDK not found) | |" }
} catch { Add-Line "| (SDK scan failed) | |" }
Add-Line ""
Add-Line "---"
Add-Line ""

# ── Python Packages (top-level count + sample) ──
Add-Line "## Python Packages"
Add-Line ""
try {
    $pipList = python -m pip list --format=freeze 2>$null
    $count = ($pipList | Measure-Object).Count
    Add-Line "Installed packages: $count"
    Add-Line ""
    Add-Line '```text'
    $pipList | Select-Object -First 40 | ForEach-Object { Add-Line $_ }
    if ($count -gt 40) { Add-Line "... ($($count - 40) more)" }
    Add-Line '```'
} catch { Add-Line "(pip list failed: $($_.Exception.Message))" }
Add-Line ""
Add-Line "---"
Add-Line ""

# ── npm Global Packages ──
Add-Line "## npm Global Packages"
Add-Line ""
try {
    $npmGlobal = npm ls -g --depth=0 2>$null
    Add-Line '```text'
    $npmGlobal | Select-Object -First 30 | ForEach-Object { Add-Line $_ }
    Add-Line '```'
} catch { Add-Line "(npm ls failed: $($_.Exception.Message))" }
Add-Line ""
Add-Line "---"
Add-Line ""

# ── Docker Images (optional) ──
Add-Line "## Docker Images"
Add-Line ""
if ($SkipDocker) {
    Add-Line "(skipped by -SkipDocker)"
} else {
    try {
        $dockerOk = Get-Command docker -ErrorAction SilentlyContinue
        if ($dockerOk) {
            $imgs = docker images --format "{{.Repository}}:{{.Tag}} ({{.Size}})" 2>$null
            if ($imgs) {
                Add-Line '```text'
                $imgs | Select-Object -First 30 | ForEach-Object { Add-Line $_ }
                Add-Line '```'
            } else { Add-Line "(no images or docker not running)" }
        } else { Add-Line "(docker not found)" }
    } catch { Add-Line "(docker query failed: $($_.Exception.Message))" }
}
Add-Line ""

[System.IO.File]::WriteAllLines($OutputPath, $lines, [System.Text.UTF8Encoding]::new($false))
Write-Host "DEPENDENCIES.md generated: $OutputPath ($($lines.Count) lines)"
